CREATE TYPE friendship_status AS ENUM ('pending', 'accepted', 'removed');
CREATE TYPE task_status AS ENUM ('todo', 'in_progress', 'done', 'archived');
CREATE TYPE task_archive_reason AS ENUM ('unfriended', 'manual_delete');

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(15) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE friend_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_a BIGINT NOT NULL REFERENCES users(id),
    user_b BIGINT NOT NULL REFERENCES users(id),
    requested_by BIGINT NOT NULL REFERENCES users(id),
    status friendship_status NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_friend_request_normalized_pair CHECK (user_a < user_b),
    CONSTRAINT chk_friend_request_requester_in_pair CHECK (requested_by = user_a OR requested_by = user_b),
    CONSTRAINT uq_friend_request_pair UNIQUE (user_a, user_b)
);

CREATE INDEX idx_friend_requests_user_a_status ON friend_requests (user_a, status);
CREATE INDEX idx_friend_requests_user_b_status ON friend_requests (user_b, status);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assigner_id BIGINT NOT NULL REFERENCES users(id),
    assignee_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL,
    description TEXT,
    due_date TIMESTAMPTZ,
    status task_status NOT NULL DEFAULT 'todo',
    archived_at TIMESTAMPTZ,
    archived_reason task_archive_reason,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_task_no_self_assignment CHECK (assigner_id <> assignee_id),
    CONSTRAINT chk_task_archival_metadata CHECK (
        (status = 'archived' AND archived_at IS NOT NULL AND archived_reason IS NOT NULL)
        OR (status <> 'archived' AND archived_at IS NULL AND archived_reason IS NULL)
    )
);

CREATE INDEX idx_tasks_assignee_active ON tasks (assignee_id, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX idx_tasks_assigner_active ON tasks (assigner_id, created_at DESC) WHERE deleted_at IS NULL;
